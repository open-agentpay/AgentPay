#!/usr/bin/env node
// Syncs repository root specs/*.md (English source of truth) to docs/specs/
// and specs/zh/*.md (Chinese source of truth, falling back to specs/*.md) to docs/zh/specs/, while:
//  1) Renaming files to site-friendly paths according to MAP
//  2) Rewriting links: inter-spec links -> relative site links; JSON/DDL/test-vectors -> GitHub links
//  3) Scrubbing local file:///Users/... paths
// Synced outputs are ignored by Git (see .gitignore); hand-written pages (index.md, reports/) are untouched.
import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC_EN = path.join(ROOT, 'specs')
const SRC_ZH = path.join(ROOT, 'specs', 'zh')
const TARGETS = [
  {
    srcDir: SRC_EN,
    outDir: path.join(ROOT, 'docs', 'specs'),
    banner: (srcRel) =>
      `<!-- This file is auto-generated by scripts/sync-specs.mjs from ${srcRel}. Do not edit directly. -->`,
  },
  {
    srcDir: SRC_ZH,
    fallbackSrcDir: SRC_EN,
    outDir: path.join(ROOT, 'docs', 'zh', 'specs'),
    banner: (srcRel) =>
      `<!-- 本文件由 scripts/sync-specs.mjs 从 ${srcRel} 自动生成，请勿直接编辑 -->`,
  },
]
const REPO = 'https://github.com/open-agentpay/AgentPay'
const BRANCH = 'main'

// Source filename -> output path under docs/specs (and docs/zh/specs).
const MAP = {
  'payment-state-machine-v2.md': 'state-machine.md',
  'wallet-ledger-spec.md': 'wallet-ledger.md',
  'protocol-consistency-spec.md': 'protocol-consistency.md',
  'config-publishing-spec.md': 'config-publishing.md',
  'audit-events-spec.md': 'audit-events.md',
  'agent-audit-spec.md': 'agent-audit.md',
  'multitenant-data-model.md': 'multitenant-data-model.md',
  'architecture.md': 'architecture.md',
  'security-model.md': 'security-model.md',
  'gas-cost-and-settlement-models.md': 'gas-models.md',
  // 'threat-model-v1.md': 'threat-model.md',
}

// Auto-detect ADRs: adr-001-xxx.md -> adr/001.md
const srcFiles = existsSync(SRC_EN) ? await readdir(SRC_EN) : []
for (const f of srcFiles) {
  const m = f.match(/^adr-(\d+).*\.md$/)
  if (m) MAP[f] = `adr/${m[1]}.md`
}

// Link rewrite map (including shorthand aliases)
const LINK_MAP = { ...MAP }
for (const f of srcFiles) {
  const m = f.match(/^adr-(\d+).*\.md$/)
  if (m) {
    LINK_MAP[`adr-${m[1]}.md`] = `adr/${m[1]}.md`
    LINK_MAP[`adr-${m[1]}`] = `adr/${m[1]}.md`
  }
}

const warnings = []
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/')

function rewriteLinks(text, srcName, outRel, outDirBase, srcDirBase) {
  const outDir = path.dirname(path.join(outDirBase, outRel))
  return text.replace(/(!?\[[^\]]*\]\()([^)\s]+)(\))/g, (all, pre, target, post) => {
    if (/^(https?:|mailto:|#)/.test(target)) return all
    let [pathPart, hash = ''] = target.split('#')
    hash = hash ? '#' + hash : ''

    // file:///Users/xxx/.../AgentPay/specs/foo.md -> repo-relative path
    pathPart = pathPart.replace(/^file:\/\/\/.*?\/AgentPay\//, '')
    const base = path.basename(pathPart)

    // 1) Link to another synced specification -> relative site link
    if (LINK_MAP[base] && !/\.json$/.test(base)) {
      const targetAbs = path.join(outDirBase, LINK_MAP[base])
      let r = path.relative(outDir, targetAbs).split(path.sep).join('/')
      if (!r.startsWith('.')) r = './' + r
      return `${pre}${r}${hash}${post}`
    }

    // 2) Other repository files -> GitHub links (try candidate base directories in order)
    const candidates = [
      path.resolve(srcDirBase, pathPart),
      path.resolve(SRC_EN, pathPart),
      path.resolve(outDirBase, pathPart),
      path.resolve(ROOT, pathPart),
    ]
    const hit = candidates.find((c) => c.startsWith(ROOT) && existsSync(c))
    if (hit) {
      const kind = !path.extname(hit) ? 'tree' : 'blob'
      return `${pre}${REPO}/${kind}/${BRANCH}/${rel(hit)}${hash}${post}`
    }
    warnings.push(`${srcName}: 无法解析链接 ${target}`)
    return all
  })
}

for (const { srcDir, fallbackSrcDir, outDir, banner } of TARGETS) {
  // Clean previous synced outputs (only delete files in MAP; leave index.md / reports/ untouched)
  for (const out of Object.values(MAP)) await rm(path.join(outDir, out), { force: true })

  let ok = 0
  for (const [srcName, outRel] of Object.entries(MAP)) {
    let srcPath = path.join(srcDir, srcName)
    let activeSrcDir = srcDir
    if (!existsSync(srcPath) && fallbackSrcDir) {
      srcPath = path.join(fallbackSrcDir, srcName)
      activeSrcDir = fallbackSrcDir
    }
    if (!existsSync(srcPath)) {
      warnings.push(`缺少源文件 ${rel(srcPath)}（跳过）`)
      continue
    }
    let text = await readFile(srcPath, 'utf8')
    text = rewriteLinks(text, srcName, outRel, outDir, activeSrcDir)
    text = `${banner(rel(srcPath))}\n\n${text}`
    const outPath = path.join(outDir, outRel)
    await mkdir(path.dirname(outPath), { recursive: true })
    await writeFile(outPath, text)
    ok++
  }
  const relOut = path.relative(ROOT, outDir).split(path.sep).join('/')
  console.log(`同步完成：${ok}/${Object.keys(MAP).length} 个规范 -> ${relOut}/`)
}

if (warnings.length) {
  console.warn('\n需要处理的问题：')
  for (const w of warnings) console.warn('  - ' + w)
}

// Fail if any local machine paths leaked
const leaked = []
for (const { outDir } of TARGETS) {
  for (const out of Object.values(MAP)) {
    const p = path.join(outDir, out)
    if (existsSync(p) && /file:\/\/\/Users|\/Users\/[a-z]+\//i.test(await readFile(p, 'utf8'))) {
      leaked.push(path.relative(ROOT, p))
    }
  }
}
if (leaked.length) {
  console.error('\n以下文件仍含本机路径：\n  ' + leaked.join('\n  '))
  process.exit(1)
}
